#!/usr/bin/env python3
"""Generate the skill catalog (docs/skills.md) from the skill index.

Reads the same source as generate-routing-map.py: the public skill index built
from SKILL.md frontmatter by generate-skill-index.py. The index is rendered to
a temporary path, so the output never depends on the gitignored local
skills/INDEX.json or on any private overlay. Skills are grouped by category
(the directory under skills/) with one row per routed skill: name,
description, and whether the skill is user-invocable (`/skill-name`).

Usage:
    python3 scripts/generate-skills-doc.py            # write docs/skills.md
    python3 scripts/generate-skills-doc.py --check    # exit 1 on findings
    python3 scripts/generate-skills-doc.py --dry-run  # print to stdout

--check mode (exit 1 on any):
    - an entry with an empty description
    - committed docs/skills.md differs from a fresh render

Private components never reach the catalog; their names are removed with the
same source of truth generate-routing-map.py uses.

Exit codes:
    0 -- generate succeeded, or --check found nothing
    1 -- --check found at least one finding, or the index could not be built
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DOC_PATH = REPO_ROOT / "docs" / "skills.md"

_SCRIPTS_DIR = Path(__file__).resolve().parent
_ROUTING_MAP = _SCRIPTS_DIR / "generate-routing-map.py"

HEADER = """\
---
summary: "Catalog of all skills by category."
read_when:
  - "browsing the skill catalog"
  - "documenting a new skill"
---

<!-- Auto-generated by scripts/generate-skills-doc.py — edit SKILL.md frontmatter, not this file. -->

# Skills

Skills are workflow methodologies — reusable process guides that tell Claude Code *how* to approach a task. Each skill lives in its own directory with a `SKILL.md` file.

Skills are invoked via `/do [request]` (routed automatically) or directly as `/skill-name`. A skill with a `/skill-name` marker in the **Invoke** column is user-invocable; the rest are internal and used by agents or other skills.

Regenerate: `python3 scripts/generate-skills-doc.py`.
CI check: `python3 scripts/generate-skills-doc.py --check`.
"""


def _escape_md(text: str) -> str:
    """Escape pipe characters and newlines for Markdown table cells."""
    return " ".join(text.split()).replace("|", "\\|")


def _private_names(repo_root: Path) -> frozenset[str]:
    """Lowercased private component names, from generate-routing-map.py's source of truth."""
    spec = importlib.util.spec_from_file_location("_generate_routing_map", _ROUTING_MAP)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {_ROUTING_MAP}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.private_names(repo_root)


def load_entries(repo_root: Path = REPO_ROOT) -> list[dict]:
    """Build the public skill index in a temp dir and return one entry per skill."""
    generator = repo_root / "scripts" / "generate-skill-index.py"
    with tempfile.TemporaryDirectory(prefix="skills-doc-") as tmp:
        out = Path(tmp) / "INDEX.json"
        subprocess.run(
            [sys.executable, str(generator), "--repo-root", str(repo_root), "--output", str(out)],
            check=True,
            capture_output=True,
        )
        try:
            raw = json.loads(out.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            raise RuntimeError(f"skill index is unreadable or malformed: {exc}") from exc
    items = raw.get("skills") if isinstance(raw, dict) else None
    if not isinstance(items, dict):
        raise RuntimeError("skill index must contain an object at 'skills'")
    entries: list[dict] = []
    for name, data in items.items():
        if not isinstance(data, dict):
            raise RuntimeError(f"skill index entry '{name}' must be an object")
        parts = Path(str(data.get("file", ""))).parts
        category = parts[1] if len(parts) > 2 else "other"
        entries.append(
            {
                "name": name,
                "description": data.get("description") or data.get("short_description", ""),
                "category": category,
                "user_invocable": bool(data.get("user_invocable", False)),
            }
        )
    return entries


def strip_private(entries: list[dict], private: frozenset[str]) -> list[dict]:
    """Drop entries whose name is a private component."""
    return [e for e in entries if str(e["name"]).lower() not in private]


def generate_doc(entries: list[dict]) -> str:
    """Render the full catalog Markdown, grouped by category."""
    by_category: dict[str, list[dict]] = {}
    for e in entries:
        by_category.setdefault(e["category"], []).append(e)
    parts = [HEADER, f"{len(entries)} routed skills.\n"]
    for category in sorted(by_category):
        group = sorted(by_category[category], key=lambda x: x["name"])
        parts.append("---\n")
        parts.append(f"## {category.replace('-', ' ').title()}\n")
        lines = ["| Skill | Description | Invoke |", "|-------|-------------|--------|"]
        for e in group:
            invoke = f"`/{e['name']}`" if e["user_invocable"] else ""
            lines.append(f"| `{e['name']}` | {_escape_md(str(e['description']))} | {invoke} |")
        parts.append("\n".join(lines))
        parts.append("")
    return "\n".join(parts)


def check_doc(entries: list[dict], doc_path: Path) -> list[str]:
    """Run --check validations. Returns a list of finding strings."""
    findings = [f"skills/{e['name']}: empty description" for e in entries if not e.get("description")]
    try:
        committed = doc_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        committed = ""
    if committed != generate_doc(entries):
        findings.append("docs/skills.md is stale (differs from a fresh render)")
    return findings


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the skill catalog.")
    parser.add_argument("--check", action="store_true", help="Validate the committed catalog; exit 1 on findings.")
    parser.add_argument("--dry-run", action="store_true", help="Print the catalog to stdout instead of writing it.")
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT, help=argparse.SUPPRESS)
    parser.add_argument("--doc-path", type=Path, default=None, help=argparse.SUPPRESS)
    args = parser.parse_args()

    doc_path = args.doc_path or (args.repo_root / "docs" / "skills.md")
    try:
        entries = strip_private(load_entries(args.repo_root), _private_names(args.repo_root))
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.check:
        findings = check_doc(entries, doc_path)
        for f in findings:
            print(f"FINDING: {f}", file=sys.stderr)
        return 1 if findings else 0

    content = generate_doc(entries)
    if args.dry_run:
        print(content)
    else:
        doc_path.parent.mkdir(parents=True, exist_ok=True)
        doc_path.write_text(content, encoding="utf-8")
        print(f"Wrote {doc_path} ({len(entries)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
