"""A copy-mode replace keeps the node_modules that ./install.sh put in each copied Jev gateway.

The engine never copies node_modules (``IGNORE_NAMES``). Before, any repo change under
``scripts/`` replaced the whole ``<root>/scripts`` copy (one entry per change under
``scripts/jev_gateway`` for per-entry targets), the old copy went to trash with its
node_modules, and /d fell back to /do until ./install.sh ran npm ci again.
"""

from __future__ import annotations

import errno
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from scripts.tests.vexinstall_support import Env, commit_all, find_named, tree_hash, world

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from vexinstall import fsops

GATEWAY = "scripts/jev_gateway"
LOCK = '{"name": "gw", "lockfileVersion": 3, "packages": {"node_modules/ai": {"version": "%s"}}}\n'
REAL_RENAME = os.rename


def _add_gateway(world: Env) -> None:
    """Ship an npm package the way the repo ships scripts/jev_gateway."""
    gateway = world.repo / GATEWAY
    gateway.mkdir(parents=True)
    (gateway / "package.json").write_text('{"name": "gw", "dependencies": {"ai": "1.0.0"}}\n', encoding="utf-8")
    (gateway / "package-lock.json").write_text(LOCK % "1.0.0", encoding="utf-8")
    (gateway / "gateway.mjs").write_text('import "ai";\n', encoding="utf-8")
    with (world.repo / ".gitignore").open("a", encoding="utf-8") as fh:
        fh.write("node_modules/\n")
    commit_all(world.repo, "add gateway")


def _npm_ci(package: Path) -> Path:
    """Leave what install.sh's npm ci leaves: a node_modules tree beside package.json."""
    modules = package / "node_modules"
    (modules / "ai").mkdir(parents=True)
    (modules / "ai" / "index.js").write_text("export default 1;\n", encoding="utf-8")
    (modules / ".package-lock.json").write_text("{}\n", encoding="utf-8")
    return modules


def _install(world: Env, target: str = "claude") -> Path:
    """Copy-install *target* with the gateway, npm ci it, and return its node_modules."""
    _add_gateway(world)
    world.root(target).mkdir(exist_ok=True)
    res = world.run("apply", "--target", target, "--mode", "copy")
    assert res.code == 0, res.err
    return _npm_ci(world.root(target) / GATEWAY)


def _change(world: Env, rel: str, text: str = "# changed\n") -> None:
    (world.repo / rel).write_text(text, encoding="utf-8")
    commit_all(world.repo, f"change {rel}")


def _trash(world: Env) -> Path:
    return world.home / ".claude" / "vexjoy" / "trash"


def _symlinks_work(tmp_path: Path) -> bool:
    try:
        os.symlink(tmp_path, tmp_path / "probe-link", target_is_directory=True)
    except OSError:
        return False
    return True


# ---------------------------------------------------------------- the replace keeps them


@pytest.mark.parametrize(
    ("target", "change"),
    [("claude", "scripts/s1.py"), ("hermes", f"{GATEWAY}/gateway.mjs")],
    ids=["whole-scripts-dir", "per-entry-gateway"],
)
def test_sync_keeps_node_modules_when_it_replaces_the_copy(world: Env, target: str, change: str) -> None:
    modules = _install(world, target)
    before = tree_hash(modules)
    _change(world, change)

    res = world.run("sync", "--target", target)
    assert res.code == 0, res.err
    assert (world.root(target) / change).read_text(encoding="utf-8") == "# changed\n"
    assert tree_hash(modules) == before
    assert res.data["node_modules"] == {"carried": [str(modules)], "warnings": []}
    assert find_named(_trash(world), "node_modules") == []


def test_kept_node_modules_never_read_as_a_user_edit(world: Env) -> None:
    """The copy hash skips node_modules, so the next source change replaces the copy again."""
    modules = _install(world)
    scripts = world.root("claude") / "scripts"
    _change(world, "scripts/s1.py")
    assert world.run("sync", "--target", "claude").code == 0

    plan = world.run("plan", "--target", "claude")
    assert [a for a in plan.data["targets"]["claude"]["actions"] if a["dest"] == str(scripts)] == []

    _change(world, "scripts/s2.py", "# s2 v2\n")
    res = world.run("sync", "--target", "claude")
    assert res.code == 0, res.err
    assert (scripts / "s2.py").read_text(encoding="utf-8") == "# s2 v2\n"
    assert res.data["node_modules"]["carried"] == [str(modules)]
    assert (modules / "ai" / "index.js").is_file()


@pytest.mark.parametrize("command", ["sync", "apply"])
def test_a_changed_lock_leaves_the_old_deps_in_trash_and_says_to_rerun_install(world: Env, command: str) -> None:
    """A node_modules always matches the lock beside it, as npm ci leaves it, so the new lock needs npm ci."""
    modules = _install(world)
    _change(world, f"{GATEWAY}/package-lock.json", LOCK % "2.0.0")

    res = world.run(command, "--target", "claude")
    assert res.code == 0, res.err
    assert not modules.exists()
    [trashed] = find_named(_trash(world), "node_modules")
    assert (trashed / "ai" / "index.js").is_file()
    expected = f"{modules} not carried over: package-lock.json changed; run ./install.sh (old one: {trashed})"
    assert f"[{command}] warning: {expected}" in res.err
    assert res.data["node_modules"] == {"carried": [], "warnings": [expected]}


def test_a_package_that_left_the_repo_leaves_its_node_modules_in_trash(world: Env) -> None:
    modules = _install(world)
    shutil.rmtree(world.repo / GATEWAY)
    commit_all(world.repo, "drop gateway")

    res = world.run("sync", "--target", "claude")
    assert res.code == 0, res.err
    assert not (world.root("claude") / GATEWAY).exists()
    [trashed] = find_named(_trash(world), "node_modules")
    assert (trashed / "ai" / "index.js").is_file()
    assert res.data["node_modules"] == {"carried": [], "warnings": []}


def test_node_modules_that_cannot_move_stay_in_trash_and_are_named(world: Env, monkeypatch: pytest.MonkeyPatch) -> None:
    """The new copy is already in place, so the entry still counts as installed and settings update."""
    modules = _install(world)
    _change(world, "scripts/s1.py")

    def rename(src: object, dst: object) -> None:
        if os.path.basename(os.fspath(src)) == "node_modules":
            raise OSError(errno.EXDEV, "Invalid cross-device link")
        REAL_RENAME(src, dst)

    monkeypatch.setattr(os, "rename", rename)
    res = world.run("sync", "--target", "claude")
    assert res.code == 0, res.err
    assert (world.root("claude") / "scripts" / "s1.py").read_text(encoding="utf-8") == "# changed\n"
    assert not modules.exists() and res.data["held_back"] == []
    [line] = [e for e in res.err if "not carried over" in e]
    [trashed] = find_named(_trash(world), "node_modules")
    assert line.startswith(f"[sync] warning: {modules} not carried over (")
    assert line.endswith(f"; run ./install.sh (old one: {trashed})") and (trashed / "ai" / "index.js").is_file()


# ---------------------------------------------------------------- a rollback brings the old copy back whole


def test_a_rollback_moves_node_modules_back_into_the_restored_copy(world: Env) -> None:
    """The apply moved them out of the copy it trashed; without the move back, --rollback left /d on /do."""
    modules = _install(world)
    old = (world.root("claude") / "scripts" / "s1.py").read_text(encoding="utf-8")
    _change(world, "scripts/s1.py")
    assert world.run("apply", "--target", "claude").data["node_modules"]["carried"] == [str(modules)]

    res = world.run("rollback")
    assert res.code == 0, res.err
    assert (world.root("claude") / "scripts" / "s1.py").read_text(encoding="utf-8") == old
    assert (modules / "ai" / "index.js").is_file()
    assert res.data["node_modules"] == {"carried": [str(modules)], "warnings": []}
    assert find_named(_trash(world), "node_modules") == []


def test_a_rollback_after_a_lock_change_brings_back_the_deps_of_the_old_lock(world: Env) -> None:
    """The old deps stayed with the old copy, so the rollback restores both, and the new ones stay in trash."""
    modules = _install(world)
    _change(world, f"{GATEWAY}/package-lock.json", LOCK % "2.0.0")
    assert world.run("apply", "--target", "claude").code == 0
    newer = _npm_ci(modules.parent)  # what install.sh's npm ci leaves for the new lock
    (newer / "ai" / "index.js").write_text("export default 2;\n", encoding="utf-8")

    res = world.run("rollback")
    assert res.code == 0, res.err
    assert (modules / "ai" / "index.js").read_text(encoding="utf-8") == "export default 1;\n"
    assert res.data["node_modules"] == {"carried": [], "warnings": []}
    [displaced] = find_named(_trash(world), "node_modules")
    assert (displaced / "ai" / "index.js").read_text(encoding="utf-8") == "export default 2;\n"


# ---------------------------------------------------------------- nothing outside the old copy moves


def test_a_switch_from_links_leaves_the_checkout_node_modules_alone(world: Env, tmp_path: Path) -> None:
    """The old entry is a link into the repo, so the node_modules behind it belong to the checkout."""
    if not _symlinks_work(tmp_path):
        pytest.skip("this host cannot create symlinks")
    _add_gateway(world)
    repo_modules = _npm_ci(world.repo / GATEWAY)
    assert world.run("apply", "--target", "claude", "--mode", "symlink").code == 0
    assert (world.root("claude") / "scripts").is_symlink()

    res = world.run("apply", "--target", "claude", "--mode", "copy")
    assert res.code == 0, res.err
    assert (repo_modules / "ai" / "index.js").is_file()
    assert not (world.root("claude") / GATEWAY / "node_modules").exists()
    assert res.data["node_modules"] == {"carried": [], "warnings": []}


@pytest.mark.skipif(os.name != "nt", reason="directory junctions are Windows-only")
@pytest.mark.parametrize("at", ["old-copy", "package-dir"])
def test_a_junction_never_lets_node_modules_from_elsewhere_move(tmp_path: Path, at: str) -> None:
    """A junction is no symlink to os.walk or os.path.islink, but it can lead into another checkout."""
    elsewhere = tmp_path / "checkout" / "scripts"
    modules = _npm_ci(elsewhere / "jev_gateway")
    old = tmp_path / "trash" / "scripts"
    link, target = (old, elsewhere) if at == "old-copy" else (old / "jev_gateway", elsewhere / "jev_gateway")
    link.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)], check=True, capture_output=True)
    new = tmp_path / "home" / "scripts"
    (new / "jev_gateway").mkdir(parents=True)
    (new / "jev_gateway" / "package.json").write_text("{}\n", encoding="utf-8")

    log = fsops.CarryLog()
    fsops.carry_node_modules(old, new, fsops.Guard(), log)
    assert (modules / "ai" / "index.js").is_file()
    assert not (new / "jev_gateway" / "node_modules").exists()
    assert log == fsops.CarryLog()
