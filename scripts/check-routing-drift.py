#!/usr/bin/env python3
"""Routing-manifest drift check.

Verifies that every skill in skills/INDEX.json and every agent in
agents/INDEX.json has an entry line in its section of the routing manifest
(generated by scripts/routing-manifest.py). A component absent from the
manifest is invisible to the router. A name that appears only inside another
entry's description does not count.

Also verifies that every indexed component's file resolves in at least one
overlay root (repo, deployed ~/.claude, private-skills). This closes the "pass
while unresolvable" hole where a component is in the manifest text but its
file exists nowhere.

Both indexes are generated, untracked artifacts (ADR untrack-generated-indexes,
local-only). This script regenerates one that is missing or older than its
sources (scripts/lib/index_freshness.py) before it validates.

Usage:
    python3 scripts/check-routing-drift.py
    python3 scripts/check-routing-drift.py --verbose

Exit codes:
    0 - Every indexed skill and agent has a manifest entry and resolves on disk
    1 - An index could not be produced or read, or a component is absent or unresolvable
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MANIFEST_SCRIPT = REPO_ROOT / "scripts" / "routing-manifest.py"

_SCRIPTS_DIR = Path(__file__).resolve().parent
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

# scripts/lib holds the shared helper; append so it shadows nothing.
sys.path.append(str(_SCRIPTS_DIR / "lib"))

from index_freshness import ensure_fresh_indexes, index_path

# Index surface -> manifest section header.
SECTIONS = {"skills": "SKILLS:", "agents": "AGENTS:"}
_SECTION_HEADER = re.compile(r"^([A-Z][A-Z-]*:)\s*$")
_ENTRY_LINE = re.compile(r"^  (\S+)")


def _ensure_indexes() -> bool:
    """Regenerate a missing or stale skills or agents index. Return False when that fails."""
    try:
        ensure_fresh_indexes(REPO_ROOT)
    except RuntimeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return False
    return True


def _build_overlay_roots() -> list[Path]:
    """Build overlay roots for SKILL.md resolution (repo, deployed, private)."""
    candidates = [
        REPO_ROOT,
        Path.home() / ".claude",
    ]
    private_root = Path.home() / "private-skills"
    if private_root.is_dir():
        candidates.append(private_root)
    return [r for r in candidates if r.exists()]


def _resolve_file(file_field: str, overlay_roots: list[Path]) -> bool:
    """Check if a component file field resolves in any overlay root."""
    for root in overlay_roots:
        if (root / file_field).is_file():
            return True
    # Deployed symlink fallback: skills/<name>/SKILL.md -> ~/.claude/skills/<name>/SKILL.md
    parts = Path(file_field).parts
    if len(parts) >= 2 and parts[0] == "skills":
        deployed = Path.home() / ".claude" / "skills" / parts[1]
        if deployed.exists():
            real = deployed.resolve()
            if (real / "SKILL.md").is_file():
                return True
    return False


def manifest_entries(manifest_text: str) -> dict[str, set[str]]:
    """Map each manifest section header to the names of its entry lines.

    An entry line starts with two spaces and the component name. Wrapped
    description lines start at column zero, so a name quoted inside another
    entry's text is not an entry.
    """
    entries: dict[str, set[str]] = {}
    current: set[str] | None = None
    for line in manifest_text.splitlines():
        header = _SECTION_HEADER.match(line)
        if header:
            current = entries.setdefault(header.group(1), set())
            continue
        entry = _ENTRY_LINE.match(line)
        if entry and current is not None:
            current.add(entry.group(1))
    return entries


def load_index(surface: str) -> dict:
    """Return the ``{name: entry}`` map of a generated index.

    Raises:
        RuntimeError: The index is unreadable or has the wrong shape.
    """
    path = index_path(REPO_ROOT, surface)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"cannot read {path}: {exc}") from exc
    items = data.get(surface) if isinstance(data, dict) else None
    if not isinstance(items, dict):
        raise RuntimeError(f"{path} must contain an object at '{surface}'")
    return items


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verbose", action="store_true", help="Show counts for every surface checked")
    args = parser.parse_args()

    if not _ensure_indexes():
        return 1

    if not MANIFEST_SCRIPT.exists():
        print(f"ERROR: {MANIFEST_SCRIPT} not found", file=sys.stderr)
        return 1

    try:
        indexes = {surface: load_index(surface) for surface in SECTIONS}
    except RuntimeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    result = subprocess.run(
        [sys.executable, str(MANIFEST_SCRIPT)],
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
    )
    if result.returncode != 0:
        print(f"ERROR: routing-manifest.py failed: {result.stderr}", file=sys.stderr)
        return 1

    rendered = manifest_entries(result.stdout)
    overlay_roots = _build_overlay_roots()
    exit_code = 0

    for surface, header in SECTIONS.items():
        items = indexes[surface]
        names = sorted(items)
        in_manifest = rendered.get(header, set())
        missing = [name for name in names if name not in in_manifest]

        if args.verbose:
            print(f"Checked {len(names)} {surface} against routing manifest section {header}")
            print(f"  Present: {len(names) - len(missing)}")
            print(f"  Missing: {len(missing)}")

        if missing:
            print(f"\nFAIL: {len(missing)} {surface} entry(ies) in INDEX.json absent from routing manifest:")
            for name in missing:
                print(f"  {name}")
            print("\nEnsure each has a valid INDEX.json entry and routing-manifest.py renders it.")
            exit_code = 1

        # Every indexed component must resolve on disk in at least one overlay
        # root. Closes the "pass while unresolvable" hole.
        unresolvable: list[str] = []
        for name, entry in items.items():
            if not isinstance(entry, dict):
                continue
            file_field = entry.get("file", "")
            if file_field and not _resolve_file(file_field, overlay_roots):
                unresolvable.append(f"  {name}: {file_field}")

        if unresolvable:
            print(f"\nFAIL: {len(unresolvable)} {surface} entry(ies) indexed but file unresolvable in any root:")
            for line in unresolvable:
                print(line)
            exit_code = 1
        elif args.verbose:
            print(f"PASS: all {len(names)} indexed {surface} resolve on disk")

    if exit_code == 0 and args.verbose:
        print("\nPASS: routing manifest is in sync with the skills and agents indexes")
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
